# [6] Exponentiation (**)
# [7] Floor Division (//)

# Addition[+]

print(10 + 30)  # Output: 40
print(-10 + 20)  # Output: 10
print(1 + 2.66)  # Output: 6.66
print(1.2 + 1.2) # Output: 2.4

# Subtraction[-]
print(60 - 30)  # Output: 30
print(-30 - 20)  # Output: -50
print(-30 - -20)  # Output: -10
print(5.66 - 3.44) # Output: 2.22

# Multiplication[*]
print(10 * 3)  # Output: 30
print(5 +10 *100)  # Output: 1005
print((5 + 10)* 100)  # Output: 1500

# Division[/]
print(100 / 20)  # Output: 5.0
print(int(100 / 20 ))  # Output: 5

# Modulus[%]
print(8 % 2)  # Output: 0
print(9 % 2)  # Output: 1
print(20 % 5)  # Output: 0
print(22 % 5)  # Output: 2

# Exponentiation[**]
print(2 ** 5)  # Output: 32
print(2 * 2 * 2 * 2 * 2)  # Output: 32
print(5 ** 4)  # Output: 81
print(5 * 5 * 5 * 5)  # Output: 625

# Floor Division[//]
print(100 // 20 )  # Output: 5
print(119 // 20)  # Output: 5
print(120 // 20)  # Output: 6
print(140 // 20)  # Output: 6
print(142 // 20)  # Output: 7



